'use strict';

// The manifest records the actual DllImport entry points (the DLL method names
// are obfuscated). Do not derive the ABI from suffixes or JavaScript arguments.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '../..');
const manifest = require('./bridge-signatures.json');
const dll = fs.readFileSync(path.join(root, manifest.assembly));
if (crypto.createHash('sha256').update(dll).digest('hex') !== manifest.sha256) {
  throw new Error('wx-runtime.dll changed: re-extract and review the PInvoke ABI before generating the bridge.');
}

const helper = `// Generated by Tools/WeChatSdk/generate-generic-bridge.cjs from the DLL ABI.
// Keep SDK-specific JSON formatting and callback routing in unity-sdk/sdk.js.
var WXGenericBridgeLibrary = {
  $WXBridge: {
    string: function(pointer) {
      return pointer ? UTF8ToString(pointer) : '';
    },
    pointer: function(value) {
      var str = value == null ? '' : String(value);
      var size = lengthBytesUTF8(str) + 1;
      var pointer = _malloc(size);
      stringToUTF8(str, pointer, size);
      return pointer;
    },
    invoke: function(name, args, fallback, failure) {
      try {
        var sdk = typeof GameGlobal !== 'undefined' && GameGlobal.WXWASMSDK;
        if (!sdk && typeof window !== 'undefined') sdk = window.WXWASMSDK;
        if (!sdk || typeof sdk[name] !== 'function') {
          throw new Error('WXWASMSDK.' + name + ' is unavailable');
        }
        return sdk[name].apply(sdk, args);
      } catch (error) {
        // JS exceptions crossing the Wasm boundary can abort Unity and cannot
        // reliably be caught by a C# try/catch. Report them here instead.
        var message = error && error.message ? error.message : String(error);
        console.error('[WX SDK bridge] ' + name + ': ' + message);
        if (failure) WXBridge.fail(failure, message);
        return fallback;
      }
    },
    fail: function(failure, error) {
      try {
        var module = typeof GameGlobal !== 'undefined' && GameGlobal.Module;
        if (!module && typeof Module !== 'undefined') module = Module;
        if (!module || typeof module.SendMessage !== 'function') return;
        if (failure.init) {
          module.SendMessage('WXSDKManagerHandler', 'Inited', 500);
          return;
        }
        var payload = { callbackId: failure.callbackId, type: 'fail',
          res: JSON.stringify({ errMsg: 'SDK bridge:fail ' + error }) };
        if (failure.id !== undefined) payload.id = failure.id;
        module.SendMessage('WXSDKManagerHandler', failure.method, JSON.stringify(payload));
        payload.type = 'complete';
        module.SendMessage('WXSDKManagerHandler', failure.method, JSON.stringify(payload));
      } catch (sendError) {
        console.error('[WX SDK bridge] Failed to report callback: ' + String(sendError));
      }
    }
  },
`;

const abiChar = type => ({ 'System.Void': 'v', 'System.String': 'i',
  'System.Double': 'd', 'System.Boolean': 'i',
  'WeChatWASM.WXSDKManagerHandler/OnBLECharacteristicValueChangeCallback': 'i' })[type];
let output = helper;
for (const entry of manifest.signatures) {
  const args = entry.parameters.map((_, index) => `a${index}`);
  const jsArgs = entry.parameters.map((type, index) => {
    if (type === 'System.String') return `WXBridge.string(a${index})`;
    if (type === 'System.Boolean') return `!!a${index}`;
    if (type === 'System.Double') return `a${index}`;
    if (type === 'WeChatWASM.WXSDKManagerHandler/OnBLECharacteristicValueChangeCallback') return `a${index}`;
    throw new Error(`Unsupported ABI type in ${entry.symbol}: ${type}`);
  });
  const jsonReturn = /WX_SyncFunction_t(?:t|nn)?$|WX_ClassOneWayNoFunction_t$/.test(entry.symbol);
  let failure = '';
  if (entry.symbol === 'WXInitializeSDK') failure = ', { init: true }';
  if (entry.symbol === 'WX_OneWayFunction') {
    failure = `, { method: params[0] + 'Callback', callbackId: params[5] }`;
  }
  if (entry.symbol === 'WX_ClassOneWayFunction') {
    failure = `, { method: '_' + params[0] + params[1] + 'Callback', id: params[2], callbackId: params[7] }`;
  }
  const fallback = entry.returns === 'System.String' ? (jsonReturn ? "'{}'" : "''") : '0';
  let body = `    var params = [${jsArgs.join(', ')}];\n`;
  let symbol = `'${entry.symbol}'`;
  if (entry.symbol === 'WX_OneWayNoFunction_vt') {
    // Preserve the SDK share module's image configuration and request ACKs.
    body += `    if (params[0] === 'ShareAppMessage') {\n      WXBridge.invoke('WXShareAppMessage', [params[1]], 0);\n      return;\n    }\n`;
  }
  const call = `WXBridge.invoke(${symbol}, params, ${fallback}${failure})`;
  if (entry.returns === 'System.Void') body += `    ${call};\n`;
  else if (entry.returns === 'System.String') body += `    return WXBridge.pointer(${call});\n`;
  else if (entry.returns === 'System.Boolean') body += `    return ${call} ? 1 : 0;\n`;
  else if (entry.returns === 'System.Double') body += `    return ${call};\n`;
  else throw new Error(`Unsupported result in ${entry.symbol}: ${entry.returns}`);
  output += `  ${entry.symbol}__deps: ['$WXBridge'],\n`;
  output += `  ${entry.symbol}__sig: '${abiChar(entry.returns)}${entry.parameters.map(abiChar).join('')}',\n`;
  output += `  ${entry.symbol}: function(${args.join(', ')}) {\n${body}  },\n`;
}
output += '};\n\nmergeInto(LibraryManager.library, WXGenericBridgeLibrary);\n';
const target = path.join(root, 'Assets/WX-WASM-SDK-V2/Runtime/Plugins/SDK-WX-Generic.jslib');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
    throw new Error('SDK-WX-Generic.jslib is out of date. Run generate-generic-bridge.cjs.');
  }
} else fs.writeFileSync(target, output);
console.log(`Verified ${manifest.signatures.length} DLL bridge signatures.`);
