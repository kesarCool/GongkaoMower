def main():
    rows = []
    row_id = START_ROW_ID
    for cat_id, key, words in cats:
        n = len(words)
        if n < 80:
            print("warn: 类别 %s (%s) 词条 %s 条（不足 80）" % (cat_id, key, n))
        seq = 0
        for w in words:
            seq += 1
            lexicon_id = THEME_PACK_ID * 100000 + cat_id * 1000 + seq
            rows.append({
                "ID": row_id,
                "lexiconId": lexicon_id,
                "DisplayText": w,
                "ThemePackId": THEME_PACK_ID,
                "CategoryTag": cat_id,
                "Weight": 1.0,
                "EffectId": 0,
                "notes": "",
            })
            row_id += 1
    fieldnames = ["ID", "lexiconId", "DisplayText", "ThemePackId", "CategoryTag", "Weight", "EffectId", "notes"]
    with open(OUTPUT, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        w.writerows(rows)
    print("wrote %s  rows=%s" % (OUTPUT, len(rows)))


if __name__ == "__main__":
    main()
