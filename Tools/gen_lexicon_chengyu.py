def main():
    rows = []
    row_id = START_ROW_ID
    for cat_id, _, words in cats:
        n = len(words)
        if n > 100:
            words = words[:100]
        if n < 100:
            print("warn: 类别 %s 词条 %s 条（不足 100）" % (cat_id, n))
        seq = 0
        for w in words:
            seq += 1
            lexicon_id = THEME_PACK_ID * 100000 + cat_id * 1000 + seq
            rows.append({
                "ID": row_id,
                "lexiconId": lexicon_id,
                "DisplayText": w,
                "ThemePackId": THEME_PACK_ID,
                "CategoryTag": cat_id,
                "Weight": 1.0,
                "EffectId": 0,
                "notes": "",
            })
            row_id += 1
    fieldnames = ["ID", "lexiconId", "DisplayText", "ThemePackId", "CategoryTag", "Weight", "EffectId", "notes"]
    with open(OUTPUT, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        w.writerows(rows)
    print("wrote", OUTPUT, "rows", len(rows))


if __name__ == "__main__":
    main()
